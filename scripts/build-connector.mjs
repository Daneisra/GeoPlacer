import { readFile, writeFile } from 'node:fs/promises';
const capture = (await readFile(new URL('../browser/geopixels-capture.js', import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
const client = (await readFile(new URL('../browser/geopixels-client.js', import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
const header = `// ==UserScript==
// @name         GeoPlacer experimental observer
// @namespace    geoplacer.local
// @version      0.1.2
// @description  Passive GeoPixels cache reader; no painting or purchases
// @match        https://geopixels.net/*
// @match        https://www.geopixels.net/*
// @grant        none
// @sandbox      raw
// @noframes
// @run-at       document-idle
// @license      AGPL-3.0-only
// ==/UserScript==
// Generated by scripts/build-connector.mjs. Edit browser/ sources.
`;
await writeFile(new URL('../public/geopixels-connector.user.js', import.meta.url), header + capture + '\n' + client);
await writeFile(new URL('../public/geopixels-capture.js', import.meta.url), capture);
