import { readFile, writeFile } from 'node:fs/promises';
const capture = (await readFile(new URL('../browser/geopixels-capture.js', import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
const client = (await readFile(new URL('../browser/geopixels-client.js', import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
const reader = (await readFile(new URL('../browser/geopixels-reader.js', import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
const transport = (await readFile(new URL('../browser/geopixels-http-transport.js', import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
const writer = (await readFile(new URL('../browser/geopixels-writer.js', import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
const version = '0.8.0';
const header = `// ==UserScript==
// @name         GeoPlacer experimental observer
// @namespace    geoplacer.local
// @version      ${version}
// @description  GeoPixels cache reader and explicitly authorized bounded sessions; no purchases
// @match        https://geopixels.net/*
// @match        https://www.geopixels.net/*
// @grant        GM_xmlhttpRequest
// @grant        GM_addElement
// @connect      127.0.0.1
// @sandbox      raw
// @noframes
// @run-at       document-idle
// @license      AGPL-3.0-only
// ==/UserScript==
// Generated by scripts/build-connector.mjs. Edit browser/ sources.
`;
await writeFile(new URL('../public/geopixels-connector.user.js', import.meta.url), header + '(() => {\nconst GeoPlacerReaderVersion = ' + JSON.stringify(version) + ';\n' + capture + '\n' + reader + '\n' + transport + '\n' + writer + '\n' + client + '\n})();\n');
await writeFile(new URL('../public/geopixels-capture.js', import.meta.url), capture);
